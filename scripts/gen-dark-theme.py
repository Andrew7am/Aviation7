"""
Writes src/theme-dark.css from Tailwind's own palette.

    python scripts/gen-dark-theme.py

Dark mode redefines every Tailwind colour variable, so no component changes.
The first version simply turned each scale over (50 <-> 950), which kept every
colour at full strength: badges glowed, red and amber text burned, and the
deep-blue greys were hard on the eyes (the user, 25 Oct 2026). This one draws
its own ramp:

  - the greys are a soft charcoal with almost no blue in them; text is a
    light grey, never pure white; the page sits a step below the cards;
  - every colour keeps its hue but loses most of its strength: the pale
    shades used for badge and row backgrounds become dark, faintly tinted
    greys, and the strong shades used for text become muted pastels.
"""
import re

src = open('node_modules/tailwindcss/theme.css', encoding='utf-8').read()
vals = dict(re.findall(r'--color-([a-z]+-\d+):\s*([^;]+);', src))
white = re.search(r'--color-white:\s*([^;]+);', src).group(1)
black = re.search(r'--color-black:\s*([^;]+);', src).group(1)
steps = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
NEUTRAL = {'slate', 'gray', 'zinc', 'neutral', 'stone', 'mauve', 'olive', 'mist', 'taupe'}

def oklch(v):
    m = re.match(r'oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)', v)
    return (float(m.group(1)) / 100, float(m.group(2)), float(m.group(3))) if m else None

# Lightness of each step in the dark ramp: low steps are backgrounds, high steps text.
GREY_L = {'50': .185, '100': .235, '200': .29, '300': .47, '400': .58, '500': .65,
          '600': .73, '700': .80, '800': .86, '900': .90, '950': .93}
TINT = {  # lightness, share of the colour's own chroma
    '50': (.245, .22), '100': (.27, .26), '200': (.31, .30), '300': (.40, .38), '400': (.60, .50),
    '500': (.66, .55), '600': (.76, .50), '700': (.81, .44), '800': (.86, .36), '900': (.90, .26), '950': (.93, .16)}

def fmt(l, c, h):
    return f'oklch({l * 100:.1f}% {c:.3f} {h:.1f})'

fams = sorted({k.rsplit('-', 1)[0] for k in vals})
dark, orig = [], []
for f in fams:
    base = oklch(vals.get(f'{f}-500', '')) or (0, 0, 0)
    for s in steps:
        k = f'{f}-{s}'
        if k not in vals:
            continue
        orig.append(f'  --color-{k}: {vals[k]};')
        if f in NEUTRAL:
            dark.append(f'  --color-{k}: {fmt(GREY_L[s], min(base[1], .012), base[2])};')
        else:
            l, share = TINT[s]
            dark.append(f'  --color-{k}: {fmt(l, base[1] * share, base[2])};')

card = fmt(.215, .006, 260)
ink = fmt(.93, .004, 260)
block = '\n'.join(dark)
out = f"""/*
 * Dark mode (the user, 25 Oct 2026). Generated by scripts/gen-dark-theme.py
 * from Tailwind's own palette - edit that script and rerun it, not this file.
 *
 * Every screen is drawn with Tailwind's colours, and in Tailwind 4 each shade
 * is a CSS variable, so dark mode is a second set of values: a soft charcoal
 * ramp for the greys (cards on white become {card}), and each colour kept in
 * its hue but quieted - pale badge backgrounds turn to dark tinted greys,
 * strong text colours to muted pastels.
 *
 * The header, the footer and the sign-in page are dark already: inside an
 * element marked keep-palette the palette is left as it was - except in a
 * panel opened from it (follow-theme), which is a page of its own.
 */
html.dark {{
  color-scheme: dark;
  --color-white: {card};
  --color-black: {ink};
{block}
}}
html.dark .keep-palette .follow-theme {{
  color-scheme: dark;
  --color-white: {card};
  --color-black: {ink};
{block}
}}
html.dark .keep-palette:not(.follow-theme) {{
  color-scheme: light;
  --color-white: {white};
  --color-black: {black};
{chr(10).join(orig)}
}}
"""
open('src/theme-dark.css', 'w', encoding='utf-8').write(out)
print(len(fams), 'families', len(dark), 'shades')
