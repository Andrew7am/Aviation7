"""
Writes src/theme-dark.css from Tailwind's own palette.

    python scripts/gen-dark-theme.py

Dark mode redefines every Tailwind colour variable, so no component changes.
The first version simply turned each scale over (50 <-> 950), which kept every
colour at full strength: badges glowed, red and amber text burned, and the
deep-blue greys were hard on the eyes (the user, 25 Oct 2026). Each look here
draws its own ramp:

  - the greys are a soft ramp; text is a light grey, never pure white; the
    page sits a step below the cards;
  - every colour keeps its hue but loses most of its strength: the pale
    shades used for badge and row backgrounds become dark, faintly tinted
    greys, and the strong shades used for text become muted pastels.

There are three looks, picked from the header; the first is the default.
"""
import re

src = open('node_modules/tailwindcss/theme.css', encoding='utf-8').read()
vals = dict(re.findall(r'--color-([a-z]+-\d+):\s*([^;]+);', src))
white = re.search(r'--color-white:\s*([^;]+);', src).group(1)
black = re.search(r'--color-black:\s*([^;]+);', src).group(1)
steps = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
NEUTRAL = {'slate', 'gray', 'zinc', 'neutral', 'stone', 'mauve', 'olive', 'mist', 'taupe'}

def oklch(v):
    m = re.match(r'oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)', v)
    return (float(m.group(1)) / 100, float(m.group(2)), float(m.group(3))) if m else None

# The greys' hue and strength, where the page, the cards and the text sit,
# and how much of its strength each colour keeps.
PRESETS = {
    # GitHub's "dark dimmed": blue-grey, low contrast, nothing pure black or white.
    'dimmed':   dict(h=250, c=.016, page=.255, card=.295, ink=.84, share=1.0),
    # Neutral graphite, no tint at all - the closest to a printed page in reverse.
    'graphite': dict(h=0,   c=.0,   page=.175, card=.215, ink=.91, share=1.0),
    # Warm charcoal, a touch of brown, the least blue light of the three.
    'warm':     dict(h=70,  c=.010, page=.195, card=.235, ink=.89, share=.85),
}

def fmt(l, c, h):
    return f'oklch({l * 100:.1f}% {c:.3f} {h:.1f})'

fams = sorted({k.rsplit('-', 1)[0] for k in vals})
orig = [f'  --color-{k}: {vals[k]};' for f in fams for k in (f'{f}-{s}' for s in steps) if k in vals]

def palette(P):
    """The variables of one look."""
    pg, cd, ink = P['page'], P['card'], P['ink']
    # Lightness of each step: low steps are backgrounds, high steps text.
    grey = {'50': pg, '100': cd + .035, '200': cd + .075, '300': cd + .22, '400': cd + .33, '500': cd + .40,
            '600': ink - .17, '700': ink - .10, '800': ink - .05, '900': ink - .02, '950': ink}
    tint = {  # lightness, share of the colour's own chroma
        '50': (cd + .03, .20), '100': (cd + .055, .24), '200': (cd + .095, .28), '300': (cd + .19, .36), '400': (.60, .48),
        '500': (.66, .52), '600': (.76, .48), '700': (.81, .42), '800': (.86, .34), '900': (.90, .24), '950': (.93, .15)}
    lines = ['  color-scheme: dark;', f"  --color-white: {fmt(cd, P['c'], P['h'])};", f"  --color-black: {fmt(ink, P['c'] / 2, P['h'])};"]
    for f in fams:
        base = oklch(vals.get(f'{f}-500', '')) or (0, 0, 0)
        for s in steps:
            k = f'{f}-{s}'
            if k not in vals:
                continue
            if f in NEUTRAL:
                lines.append(f"  --color-{k}: {fmt(grey[s], P['c'], P['h'])};")
            else:
                l, share = tint[s]
                lines.append(f"  --color-{k}: {fmt(l, base[1] * share * P['share'], base[2])};")
    return '\n'.join(lines)

blocks = []
for i, (name, P) in enumerate(PRESETS.items()):
    # The first look is the default: html.dark with no data-dark says it.
    sel = 'html.dark' if i == 0 else f'html.dark[data-dark="{name}"]'
    blocks.append(f'{sel},\n{sel} .keep-palette .follow-theme {{\n{palette(P)}\n}}')

head = """/*
 * Dark mode (the user, 25 Oct 2026). Generated by scripts/gen-dark-theme.py
 * from Tailwind's own palette - edit that script and rerun it, not this file.
 *
 * Every screen is drawn with Tailwind's colours, and in Tailwind 4 each shade
 * is a CSS variable, so dark mode is a second set of values. Three looks,
 * picked from the header (data-dark on <html>): dimmed (blue-grey, the
 * default), graphite (neutral) and warm (a touch of brown). In each, the
 * greys are a soft ramp with light-grey text, and every colour keeps its hue
 * but is quieted - pale badge backgrounds turn to dark tinted greys, strong
 * text colours to muted pastels.
 *
 * The header, the footer and the sign-in page are dark already: inside an
 * element marked keep-palette the palette is left as it was - except in a
 * panel opened from it (follow-theme), which is a page of its own.
 */
"""
keep = f"""html.dark .keep-palette:not(.follow-theme) {{
  color-scheme: light;
  --color-white: {white};
  --color-black: {black};
{chr(10).join(orig)}
}}
"""
open('src/theme-dark.css', 'w', encoding='utf-8').write(head + '\n'.join(blocks) + '\n' + keep)
print(len(PRESETS), 'looks,', len(fams), 'families')
