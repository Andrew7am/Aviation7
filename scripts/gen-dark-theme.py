import re
src = open('node_modules/tailwindcss/theme.css', encoding='utf-8').read()
vals = dict(re.findall(r'--color-([a-z]+-\d+):\s*([^;]+);', src))
white = re.search(r'--color-white:\s*([^;]+);', src).group(1); black = re.search(r'--color-black:\s*([^;]+);', src).group(1)
steps = ['50','100','200','300','400','500','600','700','800','900','950']
fams = sorted({k.rsplit('-',1)[0] for k in vals})
inv, orig = [], []
for f in fams:
    for i, s in enumerate(steps):
        k = f'{f}-{s}'; m = f'{f}-{steps[len(steps)-1-i]}'
        if k in vals and m in vals:
            inv.append(f'  --color-{k}: {vals[m]};')
            orig.append(f'  --color-{k}: {vals[k]};')
out = f"""/*
 * Dark mode (the user, 25 Oct 2026). Generated by scripts/gen-dark-theme.py from
 * Tailwind's own palette - rerun it if Tailwind's colours change.
 *
 * Every screen is drawn with Tailwind's colour scale, and in Tailwind 4 each
 * shade is a CSS variable. Dark mode turns each scale over - 50 becomes 950,
 * 100 becomes 900, and so on, 500 staying put - and white becomes the dark
 * of a card. So a white card with slate-500 text and an emerald-100 badge
 * reads as a dark card with light text and a dark emerald badge, without a
 * line of any component changing.
 *
 * The header, the footer and the sign-in page are dark already: inside an
 * element marked keep-palette the palette is left as it was - except in a
 * panel opened from it (follow-theme), which is a page of its own.
 */
html.dark {{
  color-scheme: dark;
  --color-white: {vals['slate-900']};
  --color-black: {white};
{chr(10).join(inv)}
}}
html.dark .keep-palette .follow-theme {{
  color-scheme: dark;
  --color-white: {vals['slate-900']};
  --color-black: {white};
{chr(10).join(inv)}
}}
html.dark .keep-palette:not(.follow-theme) {{
  color-scheme: light;
  --color-white: {white};
  --color-black: {black};
{chr(10).join(orig)}
}}
"""
open('src/theme-dark.css', 'w', encoding='utf-8').write(out)
print(len(fams), 'families', len(inv), 'shades')
